"""Generate a human-readable Markdown review checklist from a DocumentResult."""

from __future__ import annotations

from contract_extract.schema import DocumentResult, RiskLevel

# Human-facing field labels (Chinese+English, matching the contract-extract domain).
FIELD_LABELS = {
    "duration": "期限 / Term",
    "quantity": "数量 / Quantity",
    "price": "价格 / Price",
    "delivery": "交付 / Delivery",
    "acceptance": "验收 / Acceptance",
    "payment": "付款 / Payment",
    "penalty": "违约金 / Penalty",
    "liability_cap": "责任上限 / Liability cap",
    "confidentiality": "保密 / Confidentiality",
    "ip": "知识产权 / IP",
    "renewal": "续约 / Renewal",
    "termination": "终止 / Termination",
    "exclusivity": "排他 / Exclusivity",
    "data_protection": "数据保护 / Data protection",
    "insurance": "保险 / Insurance",
}

RISK_ICONS = {
    RiskLevel.HIGH: ":red_circle: HIGH",
    RiskLevel.MEDIUM: ":yellow_circle: MEDIUM",
    RiskLevel.LOW: ":green_circle: LOW",
}


def _all_risk(groups: list[RiskLevel]) -> RiskLevel:
    if any(r == RiskLevel.HIGH for r in groups):
        return RiskLevel.HIGH
    if any(r == RiskLevel.MEDIUM for r in groups):
        return RiskLevel.MEDIUM
    return RiskLevel.LOW


def build_checklist(
    result: DocumentResult,
) -> str:
    """Render a Markdown checklist.  Also used by the web demo."""
    lines: list[str] = []
    lines.append(f"# Contract Review Checklist")
    lines.append("")
    lines.append(f"- **Source:** `{result.source}`")
    lines.append(f"- **Format:** {result.format}  ·  **Pages:** {result.pages}  ·  "
                 f"**Engine:** {result.engine}")
    lines.append(f"- **Overall risk:** {RISK_ICONS.get(result.risk, result.risk)}")
    lines.append("")
    if result.warnings:
        lines.append("> ⚠️  " + "; ".join(result.warnings))
        lines.append("")

    # group clauses per field label
    grouped: dict[str, list] = {}
    for c in result.clauses:
        grouped.setdefault(c.clause, []).append(c)

    if not grouped:
        lines.append("No risk-relevant clauses detected by the rule layer. "
                     "This may indicate a very simple document or OCR failure.")
        return "\n".join(lines)

    lines.append("## Clauses by field")
    lines.append("")
    lines.append("| Field | Risk | Flag / detail |")
    lines.append("|---|---|---|")
    for field in sorted(grouped):
        label = FIELD_LABELS.get(field, field)
        for c in grouped[field]:
            flag = c.flag or c.detail or "—"
            lines.append(f"| **{label}** | {RISK_ICONS.get(c.risk, c.risk)} | {flag} |")
        lines.append("")

    lines.append("## Quotes with page references")
    lines.append("")
    for field in sorted(grouped):
        label = FIELD_LABELS.get(field, field)
        lines.append(f"### {label}")
        for c in grouped[field]:
            lines.append(f"- **p.{c.page}** `{c.quote}`")
            if c.flag:
                lines.append(f"  - flag: {c.flag}")
        lines.append("")

    lines.append("## Check items")
    lines.append("")
    lines.append("- [ ] Review each HIGH/MEDIUM-flagged clause. "
                 "Discuss with counsel where the flag is a hard give-away (IP assignment, uncapped liability, "
                 "automatic renewal).")
    lines.append("- [ ] Verify page references match the executed signature copy.")
    lines.append("- [ ] Consider negotiation asks for the flags above (e.g. cap penalties, "
                 "restrict IP grant-back, remove auto-renewal).")
    lines.append("")
    lines.append("---")
    lines.append("_Generated by 06-contract-extract. Machine review assists, not replaces, human judgment._")
    return "\n".join(lines)


def write_checklist(result: DocumentResult, md_path: str) -> None:
    text = build_checklist(result)
    with open(md_path, "w", encoding="utf-8") as fh:
        fh.write(text)
